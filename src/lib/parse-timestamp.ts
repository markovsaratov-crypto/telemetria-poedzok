// src/lib/parse-timestamp.ts — v2.11.0 (АУДИТ C-12): единый парсер времени для
// CSV/ZIP-импорта и инжеста. Раньше дублировался в двух роутах с разным поведением:
// ZIP-версия делала Number(iso) = NaN → BigInt(NaN) → 500 на реальных
// SensorLogger-экспортах (ISO-строки в Location.csv).
// Форматы (v2.38.2 · F74): сек (<1e10 → ×1000), мс (<1e13 → как есть),
// мкс (<1e16 → /1e3), нс (≥1e16 → /1e6), ISO-строка.
// Невалидное → null (вызывающий решает: пропустить или reject).
export function parseTimestamp(raw: string): number | null {
  const num = Number(raw);
  if (!isNaN(num) && raw.trim() !== "") {
    // v2.38.2 · F74: магнитуда-эвристика различает СЕКУНДЫ/мс/мкс/нс по порядку:
    //   < 1e10  (~1.7e9)  → секунды  → ×1000
    //   < 1e13  (~1.7e12) → миллисек → как есть
    //   < 1e16  (~1.7e15) → МИКРОсек → /1e3 (новая ветка: раньше порог ns был
    //                       «>1e15», и µs-таймстемп ~1.7e15 делился на 1e6 —
    //                       молчаливая ошибка ×1000, даты падали в 1970)
    //   ≥ 1e16  (~1.7e18) → наносек  → /1e6
    // Диапазон [1e15, 1e16) раньше давал мусор (1970-01-25 и т.п.) — теперь
    // честные µs. Семантика «мс» и «сек» для ЛЕГИТИМНЫХ значений не изменилась,
    // существующие вызовы (csv/zip/sensorlogger) получают те же мс, что раньше.
    if (num >= 1e16) return Math.floor(num / 1e6); // наносекунды
    if (num >= 1e13) return Math.floor(num / 1e3); // микросекунды
    if (num >= 1e10) return num; // мс
    if (num >= 1e9) return num * 1000; // сек → мс
    return null; // не правдоподобное число
  }
  const d = new Date(raw);
  return isNaN(d.getTime()) ? null : d.getTime();
}
